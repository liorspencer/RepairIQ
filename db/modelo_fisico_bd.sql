CREATE DATABASE repair_IQ;
USE repair_IQ;
SHOW TABLES;

CREATE TABLE EQUIPAMENTO (
    id int AUTO_INCREMENT PRIMARY KEY,
    tag varchar(10) NOT NULL,
    nome varchar(50) NOT NULL,
    tipo varchar(50) NOT NULL,
    numero_serie varchar(100),
    localizacao varchar(100),
    data_aquisicao datetime NOT NULL,
    ativo boolean NOT NULL
);

CREATE TABLE OCORRENCIA (
    id int AUTO_INCREMENT PRIMARY KEY,
    descricao varchar(1000) NOT NULL,
    status tinyint DEFAULT 0,
    prioridade tinyint NOT NULL,
    data_ocorrencia datetime DEFAULT CURRENT_TIMESTAMP,
    recomendacao_ia varchar(1000),
    FK_EQUIPAMENTO_id int
);

CREATE TABLE FUNCIONARIO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome varchar(40) not null,
    login varchar(50) not null,
    senha char(60) not null,
    ativo boolean not null,
    nivel_acesso tinyint not null
);

CREATE TABLE GRUPO_FUNCIONARIO (
    id int AUTO_INCREMENT PRIMARY KEY,
    nome_grupo varchar(30) not null ,
    descricoes varchar(300) not null
);

CREATE TABLE NOTIFICACAO (
    id int AUTO_INCREMENT PRIMARY KEY,
    data_envio datetime DEFAULT CURRENT_TIMESTAMP,
    mensagem varchar(60) not null,
    lida boolean DEFAULT 0,
    FK_FUNCIONARIO_id INT
);

CREATE TABLE REGISTRO_AUDITORIA (
    id int AUTO_INCREMENT PRIMARY KEY,
    acao varchar(300),
    data_acao datetime DEFAULT CURRENT_TIMESTAMP,
    FK_FUNCIONARIO_id INT
);

CREATE TABLE ORDEM_SERVICO (
    id int AUTO_INCREMENT PRIMARY KEY,
    data_abertura datetime,
    data_fechamento datetime,
    prioridade tinyint NOT NULL,
    status tinyint NOT NULL,
    descricao varchar(300) NOT NULL,
    conteudo text,
    recomendacao_ia varchar(1000),
    FK_EQUIPAMENTO_id int,
    FK_OCORRENCIA_id int,
    FK_MODELO_ORDEM_SERVICO_id int
);

CREATE TABLE MODELO_ORDEM_SERVICO (
    id int AUTO_INCREMENT PRIMARY KEY,
    modelo text NOT NULL
);

CREATE TABLE ORDEM_SERVICO_FUNCIONARIO (
    fk_ORDEM_SERVICO_id int,
    fk_FUNCIONARIO_id INT,
    data_inicio DATETIME DEFAULT CURRENT_TIMESTAMP,
    data_fim datetime
);

CREATE TABLE FUNCIONARIO_GRUPO_FUNCIONARIO (
    fk_FUNCIONARIO_id INT,
    fk_GRUPO_FUNCIONARIO_id int
);
 
